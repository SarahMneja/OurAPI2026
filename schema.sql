CREATE DATABASE IF NOT EXISTS OurAPI2026;

USE OurAPI2026;

-- Students table
CREATE TABLE IF NOT EXISTS Students (
    ID_S INT AUTO_INCREMENT PRIMARY KEY,
    FN VARCHAR(100) NOT NULL,
    LN VARCHAR(100) NOT NULL,
    DMjr TINYINT NOT NULL,
    Level INT NOT NULL,

    CHECK (DMjr IN (0, 1)),
    CHECK (Level IN (1, 2, 3, 4))
);

-- Reports table
CREATE TABLE IF NOT EXISTS Reports (
    ID_R INT AUTO_INCREMENT PRIMARY KEY,
    Title VARCHAR(255) NOT NULL,
    Type VARCHAR(100) NOT NULL,
    K1 VARCHAR(255) NOT NULL,
    K2 VARCHAR(255) NOT NULL,
    K3 VARCHAR(255) NOT NULL,
    Release_Date DATE NOT NULL,

    ID_S INT NOT NULL,

    FOREIGN KEY (ID_S)
        REFERENCES Students(ID_S)
        ON DELETE CASCADE
);